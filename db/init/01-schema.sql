-- REGLAS DE NIVEL DE FORMULARIO
CREATE OR REPLACE FUNCTION checku_validar_nivel_formulario()
RETURNS TRIGGER AS $$
DECLARE
    nivel VARCHAR(20);
BEGIN
    SELECT tipo_solicitud INTO nivel
      FROM solicitud_grado WHERE id_solicitud = NEW.id_solicitud FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Solicitud inexistente: %', NEW.id_solicitud USING ERRCODE = '23503';
    END IF;
    IF TG_TABLE_NAME = 'informacion_pregrado' AND nivel <> 'PREGRADO' THEN
        RAISE EXCEPTION 'Información de pregrado requiere solicitud PREGRADO' USING ERRCODE = '23514';
    ELSIF TG_TABLE_NAME IN ('informacion_posgrado', 'experiencia_laboral') AND nivel <> 'POSGRADO' THEN
        RAISE EXCEPTION 'Información de posgrado requiere solicitud POSGRADO' USING ERRCODE = '23514';
    ELSIF TG_TABLE_NAME = 'solicitud_programa' THEN
        IF nivel = 'POSGRADO' AND NEW.tipo_opcion_grado IS NOT NULL THEN
            RAISE EXCEPTION 'tipo_opcion_grado debe ser NULL en posgrado' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trg_pregrado_nivel BEFORE INSERT OR UPDATE ON informacion_pregrado FOR EACH ROW EXECUTE FUNCTION checku_validar_nivel_formulario();
CREATE OR REPLACE TRIGGER trg_posgrado_nivel BEFORE INSERT OR UPDATE ON informacion_posgrado FOR EACH ROW EXECUTE FUNCTION checku_validar_nivel_formulario();
CREATE OR REPLACE TRIGGER trg_experiencia_nivel BEFORE INSERT OR UPDATE ON experiencia_laboral FOR EACH ROW EXECUTE FUNCTION checku_validar_nivel_formulario();
CREATE OR REPLACE TRIGGER trg_programa_nivel BEFORE INSERT OR UPDATE ON solicitud_programa FOR EACH ROW EXECUTE FUNCTION checku_validar_nivel_formulario();

-- PROTECCION AL CAMBIAR DE NIVEL
CREATE OR REPLACE FUNCTION checku_validar_cambio_nivel()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.tipo_solicitud IS DISTINCT FROM OLD.tipo_solicitud THEN
        IF NEW.tipo_solicitud = 'POSGRADO' AND (
            EXISTS (SELECT 1 FROM informacion_pregrado WHERE id_solicitud = OLD.id_solicitud)
            OR EXISTS (SELECT 1 FROM solicitud_programa WHERE id_solicitud = OLD.id_solicitud AND tipo_opcion_grado IS NOT NULL)
        ) THEN
            RAISE EXCEPTION 'La solicitud conserva información exclusiva de pregrado' USING ERRCODE = '23514';
        ELSIF NEW.tipo_solicitud = 'PREGRADO' AND (
            EXISTS (SELECT 1 FROM informacion_posgrado WHERE id_solicitud = OLD.id_solicitud)
            OR EXISTS (SELECT 1 FROM experiencia_laboral WHERE id_solicitud = OLD.id_solicitud)
        ) THEN
            RAISE EXCEPTION 'La solicitud conserva información exclusiva de posgrado' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trg_solicitud_cambio_nivel BEFORE UPDATE OF tipo_solicitud ON solicitud_grado FOR EACH ROW EXECUTE FUNCTION checku_validar_cambio_nivel();


