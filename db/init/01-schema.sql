-- FUNCION Y TRIGGER PARA VALIDAR LIMITE DE 3 REENVIOS DIARIOS
CREATE OR REPLACE FUNCTION checku_validar_limite_reenvios()
RETURNS TRIGGER AS $$
DECLARE
    reenvios_hoy INTEGER;
    estudiante_id INTEGER;
BEGIN
    IF NEW.tipo_entrega = 'CORRECCION' THEN
        -- Identificar al estudiante propietario de la solicitud.
        SELECT sg.id_estudiante
          INTO estudiante_id
          FROM solicitud_grado sg
         WHERE sg.id_solicitud = NEW.id_solicitud;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'No existe la solicitud %', NEW.id_solicitud
                USING ERRCODE = '23503';
        END IF;

        -- Serializar los envíos del mismo estudiante para evitar que dos transacciones
        -- simultáneas superen el límite diario. El bloqueo se mantiene hasta el COMMIT.
        PERFORM 1
          FROM usuarios u
         WHERE u.id_usuario = estudiante_id
         FOR UPDATE;

        SELECT COUNT(*)
          INTO reenvios_hoy
          FROM entregas e
          JOIN solicitud_grado sg ON sg.id_solicitud = e.id_solicitud
         WHERE sg.id_estudiante = estudiante_id
           AND e.tipo_entrega = 'CORRECCION'
           AND e.fecha_entrega_bogota = NEW.fecha_entrega_bogota;

        IF reenvios_hoy >= 3 THEN
            RAISE EXCEPTION 'El estudiante ha alcanzado el límite máximo de 3 reenvíos por día. Intente nuevamente mañana.'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE OR REPLACE TRIGGER trg_limite_reenvios
BEFORE INSERT ON entregas
FOR EACH ROW EXECUTE FUNCTION checku_validar_limite_reenvios();

