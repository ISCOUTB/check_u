-- CHECKU | Esquema de Base de Datos Actualizado
-- PostgreSQL 14 o superior.
-- Incluye control de entregas, limite diario de reenvios, estados procesales y soporte multi-documento.
BEGIN;

-- 1. USUARIOS
CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    correo VARCHAR(150) NOT NULL,
    rol VARCHAR(30) NOT NULL,
    codigo_estudiante TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuarios_correo UNIQUE (correo),
    CONSTRAINT uq_usuarios_codigo_estudiante UNIQUE (codigo_estudiante),
    CONSTRAINT chk_usuarios_estudiante_con_codigo CHECK (
        rol <> 'ESTUDIANTE' OR
        (codigo_estudiante IS NOT NULL AND btrim(codigo_estudiante) <> '')
    ),
    CONSTRAINT chk_usuarios_codigo_no_vacio CHECK (
        codigo_estudiante IS NULL OR btrim(codigo_estudiante) <> ''
    ),
    CONSTRAINT chk_usuarios_rol CHECK (rol IN ('ESTUDIANTE', 'FUNCIONARIO', 'BIBLIOTECA'))
);

-- 2. SOLICITUD_GRADO
CREATE TABLE IF NOT EXISTS solicitud_grado (
    id_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_estudiante INTEGER NOT NULL,
    tipo_solicitud VARCHAR(20) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'BORRADOR',
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_solicitud_grado PRIMARY KEY (id_solicitud),
    CONSTRAINT fk_solicitud_estudiante FOREIGN KEY (id_estudiante)
        REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT chk_tipo_solicitud CHECK (tipo_solicitud IN ('PREGRADO', 'POSGRADO')),
    CONSTRAINT chk_estado_solicitud CHECK (
        estado IN ('BORRADOR', 'EN_PROCESO', 'POR_REVISAR', 'VALIDA', 'NO_VALIDA', 'INCONSISTENTE', 'CERRADA')
    )
);

-- 2.1. PERIODOS_GRADO
-- Ventanas de recepción de solicitudes de grado.
-- ABIERTO permite recibir solicitudes; CERRADO conserva el periodo para consulta histórica.
CREATE TABLE IF NOT EXISTS periodos_grado (
    id UUID PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    fecha_graduacion DATE NOT NULL,
    estado VARCHAR(10) NOT NULL DEFAULT 'ABIERTO',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT periodos_grado_fechas_validas CHECK (fecha_inicio <= fecha_fin),
    CONSTRAINT periodos_grado_estado_valido CHECK (estado IN ('ABIERTO', 'CERRADO'))
);

-- Compatibilidad con bases donde la tabla se creó con una versión anterior.
ALTER TABLE periodos_grado
    ADD COLUMN IF NOT EXISTS fecha_graduacion DATE;

ALTER TABLE periodos_grado
    ADD COLUMN IF NOT EXISTS estado VARCHAR(10) NOT NULL DEFAULT 'ABIERTO';

-- Los registros antiguos no tenían fecha de ceremonia: usar fecha_fin como respaldo inicial.
UPDATE periodos_grado
SET fecha_graduacion = fecha_fin
WHERE fecha_graduacion IS NULL;

ALTER TABLE periodos_grado
    ALTER COLUMN fecha_graduacion SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'periodos_grado_estado_valido'
    ) THEN
        ALTER TABLE periodos_grado
            ADD CONSTRAINT periodos_grado_estado_valido
            CHECK (estado IN ('ABIERTO', 'CERRADO'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_periodos_grado_fechas
    ON periodos_grado (fecha_inicio DESC, fecha_fin DESC);

CREATE INDEX IF NOT EXISTS idx_periodos_grado_estado
    ON periodos_grado (estado, fecha_inicio DESC);

-- 3. ENTREGAS (Control de envíos, límites diarios y trazabilidad)
CREATE TABLE IF NOT EXISTS entregas (
    id_entrega INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud INTEGER NOT NULL,
    numero_entrega INTEGER NOT NULL DEFAULT 1,
    tipo_entrega VARCHAR(20) NOT NULL DEFAULT 'INICIAL',
    fecha_entrega TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_entrega_bogota DATE NOT NULL DEFAULT (
        (CURRENT_TIMESTAMP AT TIME ZONE 'America/Bogota')::DATE
    ),

    observacion_estudiante TEXT,

    CONSTRAINT pk_entregas PRIMARY KEY (id_entrega),

    CONSTRAINT fk_entrega_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud_grado(id_solicitud) ON DELETE RESTRICT,

    CONSTRAINT uq_entrega_solicitud_numero
        UNIQUE (id_solicitud, numero_entrega),

    CONSTRAINT chk_tipo_entrega
        CHECK (tipo_entrega IN ('INICIAL', 'CORRECCION')),

    CONSTRAINT chk_numero_entrega
        CHECK (numero_entrega >= 1)
);

-- 4. DOCUMENTOS (Vinculados a entregas y con soporte para orden/múltiples archivos)
CREATE TABLE IF NOT EXISTS documentos (
    id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud INTEGER NOT NULL,
    id_entrega INTEGER, -- NULL mientras esté en BORRADOR; se asigna al enviar la entrega
    tipo_documento VARCHAR(50) NOT NULL,
    orden SMALLINT NOT NULL DEFAULT 1, -- Permite diferenciar múltiples comprobantes (ej. Estampilla 1 y 2 en doble programa)
    nombre_original VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    tamano_bytes INTEGER NOT NULL,
    hash_archivo VARCHAR(255),
    version INTEGER NOT NULL DEFAULT 1,
    estado VARCHAR(30) NOT NULL DEFAULT 'CARGADO',
    fecha_carga TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_documentos PRIMARY KEY (id_documento),
    CONSTRAINT fk_documento_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud_grado(id_solicitud) ON DELETE RESTRICT,
    CONSTRAINT fk_documento_entrega FOREIGN KEY (id_entrega)
        REFERENCES entregas(id_entrega) ON DELETE RESTRICT,
    CONSTRAINT uq_documento_version UNIQUE (id_solicitud, tipo_documento, orden, version),
    CONSTRAINT chk_documento_orden CHECK (orden BETWEEN 1 AND 2),
    CONSTRAINT chk_documento_version CHECK (version >= 1),
    CONSTRAINT chk_documento_tamano CHECK (tamano_bytes > 0),
    CONSTRAINT chk_documento_estado CHECK (
        estado IN ('CARGADO', 'POR_VALIDAR', 'VALIDO', 'NO_VALIDO', 'INCONSISTENTE')
    )
);

-- 5. RUTAS
CREATE TABLE IF NOT EXISTS rutas (
    id_ruta INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_documento INTEGER NOT NULL,
    ruta_archivo VARCHAR(500) NOT NULL,
    nombre_archivo_servidor VARCHAR(255) NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_rutas PRIMARY KEY (id_ruta),
    CONSTRAINT fk_ruta_documento FOREIGN KEY (id_documento)
        REFERENCES documentos(id_documento) ON DELETE RESTRICT
);

-- 6. VALIDACIONES (Resultados generados por el Motor de OCR y Reglas)
CREATE TABLE IF NOT EXISTS validaciones (
    id_validacion INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_documento INTEGER NOT NULL,
    tipo_validacion VARCHAR(50) NOT NULL,
    resultado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    mensaje TEXT,
    confianza NUMERIC(5,2),
    fecha_validacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_validaciones PRIMARY KEY (id_validacion),
    CONSTRAINT fk_validacion_documento FOREIGN KEY (id_documento)
        REFERENCES documentos(id_documento) ON DELETE RESTRICT,
    CONSTRAINT chk_validacion_tipo CHECK (
        tipo_validacion IN ('OCR', 'INTEGRIDAD', 'CONSISTENCIA', 'REQUISITOS', 'FIRMA_CRIPTOGRAFICA')
    ),
    CONSTRAINT chk_validacion_resultado CHECK (
        resultado IN ('PENDIENTE', 'VALIDO', 'NO_VALIDO', 'INCONSISTENTE')
    ),
    CONSTRAINT chk_validacion_confianza CHECK (confianza BETWEEN 0 AND 100)
);

-- 7. HISTORIAL_VALIDACIONES
CREATE TABLE IF NOT EXISTS historial_validaciones (
    id_historial INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_validacion INTEGER NOT NULL,
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30) NOT NULL,
    observacion TEXT,
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_historial_validaciones PRIMARY KEY (id_historial),
    CONSTRAINT fk_historial_validacion FOREIGN KEY (id_validacion)
        REFERENCES validaciones(id_validacion) ON DELETE RESTRICT,
    CONSTRAINT chk_historial_estado_nuevo CHECK (
        estado_nuevo IN ('PENDIENTE', 'VALIDO', 'NO_VALIDO', 'INCONSISTENTE')
    ),
    CONSTRAINT chk_historial_estado_anterior CHECK (
        estado_anterior IS NULL OR estado_anterior IN ('PENDIENTE', 'VALIDO', 'NO_VALIDO', 'INCONSISTENTE')
    )
);

-- 8. REVISIONES (Intervención del Funcionario de Grados o Biblioteca)
CREATE TABLE IF NOT EXISTS revisiones (
    id_revision INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud INTEGER NOT NULL,
    id_funcionario INTEGER NOT NULL,
    resultado VARCHAR(30) NOT NULL,
    comentario TEXT,
    fecha_revision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_revisiones PRIMARY KEY (id_revision),
    CONSTRAINT fk_revision_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud_grado(id_solicitud) ON DELETE RESTRICT,
    CONSTRAINT fk_revision_funcionario FOREIGN KEY (id_funcionario)
        REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT chk_revision_resultado CHECK (
        resultado IN ('APROBADA', 'CORRECCION_REQUERIDA', 'RECHAZADA', 'POR_REVISAR')
    )
);

-- 9. PERFIL_ESTUDIANTE
CREATE TABLE IF NOT EXISTS perfil_estudiante (
    id_usuario INTEGER NOT NULL,
    tipo_documento_identidad TEXT NOT NULL,
    numero_documento TEXT NOT NULL,
    fecha_nacimiento DATE,
    genero TEXT,
    departamento_residencia TEXT,
    ciudad_residencia TEXT,
    direccion_residencia TEXT,
    telefono_fijo TEXT,
    telefono_celular TEXT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_perfil_estudiante PRIMARY KEY (id_usuario),
    CONSTRAINT fk_perfil_estudiante_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT uq_perfil_estudiante_identidad
        UNIQUE (tipo_documento_identidad, numero_documento),
    CONSTRAINT chk_perfil_tipo_documento_no_vacio
        CHECK (btrim(tipo_documento_identidad) <> ''),
    CONSTRAINT chk_perfil_numero_documento
        CHECK (numero_documento ~ '^[A-Za-z0-9]+$')
