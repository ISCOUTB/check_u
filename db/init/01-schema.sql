-- FUNCION Y TRIGGER PARA VALIDAR LIMITE DE 3 REENVIOS DIARIOS
CREATE OR REPLACE FUNCTION checku_validar_limite_reenvios()
RETURNS TRIGGER AS $$
DECLARE
    reenvios_hoy INTEGER;
BEGIN
    IF NEW.tipo_entrega = 'CORRECCION' THEN
        SELECT COUNT(*) INTO reenvios_hoy
        FROM entregas
        WHERE id_solicitud = NEW.id_solicitud
          AND tipo_entrega = 'CORRECCION'
          AND fecha_entrega_bogota = NEW.fecha_entrega_bogota;

        IF reenvios_hoy >= 3 THEN
            RAISE EXCEPTION 'Ha alcanzado el límite máximo de 3 reenvíos por día. Intente nuevamente mañana.'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trg_limite_reenvios
BEFORE INSERT ON entregas
FOR EACH ROW EXECUTE FUNCTION checku_validar_limite_reenvios();

-- ACTUALIZACION AUTOMATICA DE FECHA_ACTUALIZACION
CREATE OR REPLACE FUNCTION checku_actualizar_fecha()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

