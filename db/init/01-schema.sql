ALTER TABLE documentos
    ADD CONSTRAINT chk_documento_estado
    CHECK (estado IN ('CARGADO', 'POR_VALIDAR', 'VALIDO', 'NO_VALIDO', 'INCONSISTENTE', 'POR_REVISAR'));

