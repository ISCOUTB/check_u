BEGIN;
CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    solicitud_id INTEGER REFERENCES solicitud_grado(id_solicitud) ON DELETE RESTRICT,
    documento_id INTEGER REFERENCES documentos(id_documento) ON DELETE RESTRICT,
    revision_id INTEGER REFERENCES revisiones(id_revision) ON DELETE RESTRICT,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('success','warning','error','info')),
    titulo VARCHAR(150) NOT NULL CHECK (btrim(titulo) <> ''),
    msg TEXT NOT NULL CHECK (btrim(msg) <> ''),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    generado_por VARCHAR(12) NOT NULL CHECK (generado_por IN ('system','motor','funcionario')),
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    clave_evento VARCHAR(200) NOT NULL UNIQUE CHECK (btrim(clave_evento) <> '')
);
CREATE INDEX IF NOT EXISTS idx_notificaciones_estudiante_fecha ON notificaciones(estudiante_id, creado_en DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_notificaciones_no_leidas ON notificaciones(estudiante_id) WHERE NOT leida;

-- Los identificadores permiten describir los documentos de una revisión sin inventar su lista.
ALTER TABLE revisiones ADD COLUMN IF NOT EXISTS documentos_ids INTEGER[];

CREATE OR REPLACE FUNCTION nombre_documento_notificacion(tipo TEXT, orden INTEGER) RETURNS TEXT
LANGUAGE SQL IMMUTABLE AS $$
    SELECT CASE tipo WHEN 'identification' THEN 'Documento de identidad'
      WHEN 'academic_evaluation' THEN 'Evaluación de Grado (Banner)'
      WHEN 'paz_y_salvo_bib' THEN 'Paz y Salvo de Biblioteca'
      WHEN 'saber_pro' THEN 'Resultados Saber Pro'
      WHEN 'estampilla_pro_cultura' THEN 'Estampilla Pro-Cultura'
      ELSE 'Documento' END || CASE WHEN orden=2 THEN ' (segundo programa)' ELSE '' END
$$;

-- Punto único de inserción para el servicio Nest y los eventos persistidos de revisiones.
CREATE OR REPLACE FUNCTION crear_notificacion(
    destinatario INTEGER, clase TEXT, encabezado TEXT, mensaje TEXT, actor TEXT, clave TEXT,
    solicitud INTEGER DEFAULT NULL, documento INTEGER DEFAULT NULL, revision INTEGER DEFAULT NULL
) RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE creado BIGINT;
BEGIN
    IF NOT EXISTS(SELECT 1 FROM usuarios WHERE id_usuario=destinatario AND rol='ESTUDIANTE') THEN
        RAISE EXCEPTION 'Destinatario de notificación inválido';
    END IF;
    IF solicitud IS NOT NULL AND NOT EXISTS(SELECT 1 FROM solicitud_grado WHERE id_solicitud=solicitud AND id_estudiante=destinatario) THEN
        RAISE EXCEPTION 'La notificación no corresponde a la solicitud del estudiante';
    END IF;
    IF documento IS NOT NULL AND NOT EXISTS(SELECT 1 FROM documentos WHERE id_documento=documento AND id_solicitud=solicitud) THEN
        RAISE EXCEPTION 'El documento no corresponde a la solicitud';
    END IF;
    IF revision IS NOT NULL AND NOT EXISTS(SELECT 1 FROM revisiones WHERE id_revision=revision AND id_solicitud=solicitud) THEN
        RAISE EXCEPTION 'La revisión no corresponde a la solicitud';
    END IF;
    INSERT INTO notificaciones(estudiante_id,tipo,titulo,msg,generado_por,clave_evento,solicitud_id,documento_id,revision_id)
    VALUES(destinatario,clase,encabezado,mensaje,actor,clave,solicitud,documento,revision)
    ON CONFLICT(clave_evento) DO NOTHING RETURNING id INTO creado;
    IF creado IS NULL THEN
        SELECT n.id INTO creado FROM notificaciones n WHERE n.clave_evento=clave AND n.estudiante_id=destinatario;
        IF creado IS NULL THEN RAISE EXCEPTION 'Clave de notificación incompatible'; END IF;
    END IF;
    RETURN creado;
END $$;

CREATE OR REPLACE FUNCTION notificar_revision() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE estudiante INTEGER; lista TEXT; total INTEGER; clase TEXT; encabezado TEXT; mensaje TEXT;
BEGIN
    IF NOT EXISTS(SELECT 1 FROM usuarios WHERE id_usuario=NEW.id_funcionario AND rol='FUNCIONARIO') THEN
        RAISE EXCEPTION 'La revisión requiere un funcionario';
    END IF;
    SELECT id_estudiante INTO estudiante FROM solicitud_grado WHERE id_solicitud=NEW.id_solicitud;
    IF NEW.resultado='APROBADA' THEN
        clase:='info'; encabezado:='Solicitud aceptada'; mensaje:='Tu solicitud de grado fue aceptada.';
    ELSIF NEW.resultado='RECHAZADA' THEN
        clase:='error'; encabezado:='Solicitud anulada'; mensaje:='Tu solicitud fue anulada. Incumpliste ciertos requisitos.';
    ELSIF NEW.resultado='CORRECCION_REQUERIDA' THEN
        IF COALESCE(cardinality(NEW.documentos_ids),0)=0 THEN RAISE EXCEPTION 'Selecciona los documentos de la corrección'; END IF;
        SELECT count(*), string_agg(nombre_documento_notificacion(d.tipo_documento,d.orden), ', ' ORDER BY d.tipo_documento,d.orden)
        INTO total,lista FROM documentos d WHERE d.id_solicitud=NEW.id_solicitud AND d.id_documento=ANY(NEW.documentos_ids) AND d.id_entrega IS NOT NULL;
        IF total<>cardinality(NEW.documentos_ids) THEN RAISE EXCEPTION 'Documentos de revisión inválidos'; END IF;
        clase:='warning'; encabezado:='Documentos por volver a subir';
        mensaje:='La funcionaria confirmó que necesitas volver a subir estos documentos: '||lista||'.';
    ELSIF NEW.resultado='POR_REVISAR' AND COALESCE(btrim(NEW.comentario),'')<>'' THEN
        clase:='info'; encabezado:='Nuevo comentario';
        mensaje:='La funcionaria te dejó un comentario: '||left(NEW.comentario,15)||CASE WHEN char_length(NEW.comentario)>15 THEN '…' ELSE '' END;
    ELSE RETURN NEW;
    END IF;
    PERFORM crear_notificacion(estudiante,clase,encabezado,mensaje,'funcionario','revision:'||NEW.id_revision,NEW.id_solicitud,NULL,NEW.id_revision);
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_notificar_revision ON revisiones;
CREATE TRIGGER trg_notificar_revision AFTER INSERT ON revisiones FOR EACH ROW EXECUTE FUNCTION notificar_revision();
COMMIT;
