-- Idempotente: se puede aplicar sobre una base existente sin borrar datos.

BEGIN;

CREATE TABLE IF NOT EXISTS opciones_campo (
    id_opcion INTEGER GENERATED BY DEFAULT AS IDENTITY,
    campo VARCHAR(30) NOT NULL,
    valor VARCHAR(80) NOT NULL,
    etiqueta VARCHAR(150) NOT NULL,
    orden SMALLINT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_opciones_campo PRIMARY KEY (id_opcion),
    CONSTRAINT chk_opciones_campo_campo CHECK (
        campo IN ('TIPO_DOCUMENTO', 'GENERO', 'PROGRAMA', 'OPCION_GRADO', 'TIPO_DISCAPACIDAD')
    ),
    CONSTRAINT chk_opciones_campo_valor CHECK (btrim(valor) <> ''),
    CONSTRAINT chk_opciones_campo_etiqueta CHECK (btrim(etiqueta) <> ''),
    CONSTRAINT chk_opciones_campo_orden CHECK (orden >= 1),
    CONSTRAINT uq_opciones_campo_valor UNIQUE (campo, valor)
);

-- El nombre visible no se repite dentro de un mismo campo (sin distinguir mayúsculas).
CREATE UNIQUE INDEX IF NOT EXISTS uq_opciones_campo_etiqueta
    ON opciones_campo (campo, lower(etiqueta));

CREATE INDEX IF NOT EXISTS idx_opciones_campo_orden
    ON opciones_campo (campo, orden);

-- El tipo de discapacidad deja de ser un catálogo cerrado en el perfil: ahora lo
-- administra el funcionario desde opciones_campo. Se conservan las reglas de
-- coherencia entre la respuesta principal y los campos dependientes.
ALTER TABLE perfil_estudiante
    DROP CONSTRAINT IF EXISTS chk_perfil_discapacidad;

ALTER TABLE perfil_estudiante
    ADD CONSTRAINT chk_perfil_discapacidad CHECK (
        (tiene_discapacidad IS TRUE AND
         tipo_discapacidad IS NOT NULL AND
         btrim(tipo_discapacidad) <> '')
        OR
        (tiene_discapacidad IS NOT TRUE AND
         tipo_discapacidad IS NULL AND
         detalles_necesidades_asistencia IS NULL)
    );

